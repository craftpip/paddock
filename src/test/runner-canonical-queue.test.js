    detail = await mission.readRunnerQueue(runner.id);
    paused = mission.getRunner(runner.id);
    assert.equal(paused.pause_state, 'confirmed');
    assert.equal(detail.runner.pause_state, 'confirmed');
    assert.equal(detail.queue.items[0].status, 'in progress', 'confirmation preserves the worker checkpoint');
