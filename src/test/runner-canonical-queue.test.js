it('serializes queue projection publishers across independent webui processes', async () => {
  const project = mission.createProject({ name: 'publisher-lease', agent: PAD, folder: FOLDER, plansFolder: 'plans' });
  const session = mission.createSession(project.id, { agentSessionId: 'ses_publisher_lease' });
  const runner = await mission.createRunner({ projectId: project.id, name: 'publisher-lease', sessionId: session.id });
  const agent = registry.getAgent(PAD);
  const outputPath = plans.queuePath(agent, project);
  const before = fs.readFileSync(outputPath, 'utf8');
  const readyFile = path.join(root, 'publisher-held.ready');
  const gateFile = path.join(root, 'publisher-held.go');
  const service = path.resolve(__dirname, '../services/runner-publication');
  const script = `
    const fs = require('node:fs');
    const publication = require(${JSON.stringify(service)});
    publication.withPublisherLease(process.env.RUNNER_ID, () => {
      fs.writeFileSync(process.env.READY_FILE, 'held');
      const wait = new Int32Array(new SharedArrayBuffer(4));
      const deadline = Date.now() + 10000;
      while (!fs.existsSync(process.env.GATE_FILE) && Date.now() < deadline) Atomics.wait(wait, 0, 0, 5);
      if (!fs.existsSync(process.env.GATE_FILE)) process.exitCode = 2;
    });
  `;
  const child = spawn(process.execPath, ['-e', script], {
    cwd: path.resolve(__dirname, '..'),
    env: { ...process.env, RUNNER_ID: runner.id, READY_FILE: readyFile, GATE_FILE: gateFile },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  let stderr = '';
  child.stderr.on('data', (chunk) => { stderr += chunk; });
  const exited = new Promise((resolve, reject) => {
    child.on('error', reject);
    child.on('close', (code) => code === 0 ? resolve() : reject(new Error(`publisher child exited ${code}: ${stderr}`)));
  });
  try {
    const deadline = Date.now() + 5000;
    while (!fs.existsSync(readyFile) && Date.now() < deadline) await new Promise((resolve) => setTimeout(resolve, 10));
    assert.ok(fs.existsSync(readyFile), 'the independent publisher acquired its database lease');
    assert.throws(() => runnerPublication.publish(runner, project, agent), { code: 'runner_publication_busy' });
    assert.equal(fs.readFileSync(outputPath, 'utf8'), before, 'a refused publisher performs no filesystem write');
  } finally {
    fs.writeFileSync(gateFile, 'release');
    await exited;
  }
  const published = runnerPublication.publish(runner, project, agent);
  assert.equal(published.revision, 0);
  assert.equal(runnerPublication.read(runner.id).acknowledged_revision, 0);
});

