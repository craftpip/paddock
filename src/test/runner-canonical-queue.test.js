const { after, beforeEach, it } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'runner-canonical-queue-'));
process.env.WORKSPACE_ROOT = root;
process.env.PAD_DB_PATH = path.join(root, 'queue.db');
const PAD = 'pad-canonical-queue';
const FOLDER = '/root/.opencode/workspace';
fs.mkdirSync(path.join(root, 'instances', PAD), { recursive: true });
fs.writeFileSync(path.join(root, 'instances', PAD, 'meta.env'), 'AGENT=opencode\n');

const { getDb } = require('../services/db');
const mission = require('../services/mission');
const plans = require('../services/plans');
const registry = require('../services/agent-registry');

after(() => fs.rmSync(root, { recursive: true, force: true }));

beforeEach(() => {
  const db = getDb();
  db.exec('DELETE FROM runner_queue_events; DELETE FROM runner_queue_items; DELETE FROM runner_queues; DELETE FROM infinite_runners; DELETE FROM mission_sessions; DELETE FROM mission_projects; DELETE FROM agents;');
  db.prepare("INSERT INTO agents (id, name, agent_type, runtime_type, runtime_ref, status) VALUES (?, ?, 'opencode', 'docker', ?, 'running')").run(PAD, PAD, PAD);
  fs.rmSync(path.join(root, 'instances', PAD, 'opencode', 'workspace'), { recursive: true, force: true });
});

it('serves canonical queue rows and regenerates the worker projection after every mutation', async () => {
  const project = mission.createProject({ name: 'canonical', agent: PAD, folder: FOLDER, plansFolder: 'plans' });
  const session = mission.createSession(project.id, { agentSessionId: 'ses_canonical' });
  const runner = await mission.createRunner({ projectId: project.id, name: 'canonical', sessionId: session.id });
  let detail = await mission.readRunnerQueue(runner.id);
  assert.equal(detail.queue.condition, 'ok');
  assert.equal(detail.queue.revision, 0);
  detail = await mission.addRunnerQueueItems(runner.id, ['one.md', 'two.md'], detail.queue.revision);
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['one.md', 'two.md']);
  assert.ok(detail.queue.items.every((item) => !item.id.startsWith('q-')));
  const projection = fs.readFileSync(plans.queuePath(registry.getAgent(PAD), project), 'utf8');
  assert.match(projection, /Generated by Paddock/);
  assert.match(projection, /one\.md/);
  fs.appendFileSync(plans.queuePath(registry.getAgent(PAD), project), 'external edit');
  detail = await mission.readRunnerQueue(runner.id);
  assert.equal(detail.queue.condition, 'projection_error');
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['one.md', 'two.md']);
  await assert.rejects(
    mission.startRunner(runner.id),
    (error) => error.code === 'runner_invalid_queue' && error.message.includes('Generated QUEUE.md differs')
  );
  detail = await mission.setupRunnerQueue(runner.id);
  assert.equal(detail.queue.condition, 'ok');
  detail = await mission.removeRunnerQueueItem(runner.id, detail.queue.items[0].id, detail.queue.revision);
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['two.md']);
});
