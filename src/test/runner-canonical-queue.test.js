it('serves canonical queue rows and regenerates the worker projection after every mutation', async () => {
  const project = mission.createProject({ name: 'canonical', agent: PAD, folder: FOLDER, plansFolder: 'plans' });
  const session = mission.createSession(project.id, { agentSessionId: 'ses_canonical' });
  const runner = await mission.createRunner({ projectId: project.id, name: 'canonical', sessionId: session.id });
  let detail = await mission.readRunnerQueue(runner.id);
  assert.equal(detail.queue.condition, 'ok');
  assert.equal(detail.queue.revision, 0);
  assert.equal(detail.queue.execution.state, 'paused');
  assert.equal('canonicalState' in detail.runner, false, 'the queue runner metadata does not duplicate its execution verdict');
  const publicRunner = mission.publicRunner(mission.getRunner(runner.id));
  assert.equal(publicRunner.execution.state, 'paused');
  for (const legacyField of ['enabled', 'control_state', 'run_generation', 'operation_id', 'operation_status', 'stop_cause']) {
    assert.equal(Object.hasOwn(publicRunner, legacyField), false, `${legacyField} is not part of the public runner contract`);
  }
  const publication = runnerPublication.read(runner.id);
  assert.equal(publication.desired_revision, 0);
  assert.equal(publication.acknowledged_revision, 0);
  detail = await mission.addRunnerQueueItems(runner.id, ['one.md', 'two.md'], detail.queue.revision);
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['one.md', 'two.md']);
  assert.ok(detail.queue.items.every((item) => !item.id.startsWith('q-')));
  const projection = fs.readFileSync(plans.queuePath(registry.getAgent(PAD), project), 'utf8');
  assert.match(projection, /Generated by Paddock/);
  assert.match(projection, /one\.md/);
  runnerTransition.applyRun(runner.id);
  fs.appendFileSync(plans.queuePath(registry.getAgent(PAD), project), 'external edit');
  detail = await mission.readRunnerQueue(runner.id);
  assert.equal(detail.queue.condition, 'projection_error');
  assert.equal(detail.queue.execution.label, 'Queue file out of sync');
  assert.equal(detail.queue.execution.actions.run.allowed, false);
  assert.equal(detail.queue.execution.actions.reconcile.allowed, false);
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['one.md', 'two.md']);
  assert.match(fs.readFileSync(plans.queuePath(registry.getAgent(PAD), project), 'utf8'), /external edit/,
    'an integrity read must never silently repair the worker projection');
  await assert.rejects(
    mission.startRunner(runner.id),
    (error) => error.code === 'runner_invalid_queue' && error.message.includes('Regenerate')
  );
  assert.equal(runnerTransition.getRuntime(runner.id).state, 'projection_error');
  await assert.rejects(mission.reconcileRunnerOperation(runner.id), { code: 'runner_invalid_queue' });
  await assert.rejects(mission.setupRunnerQueue(runner.id), { code: 'runner_projection_confirmation_required' });
  assert.match(fs.readFileSync(plans.queuePath(registry.getAgent(PAD), project), 'utf8'), /external edit/);
  detail = await mission.setupRunnerQueue(runner.id, { confirmProjectionReset: true });
  assert.equal(detail.queue.condition, 'ok');
  assert.equal(detail.queue.execution.state, 'paused');
  assert.equal(detail.queue.execution.actions.run.allowed, true);
  assert.equal(mission.getRunner(runner.id).operation_status, 'invalidated');
  assert.equal(mission.getRunner(runner.id).enabled, 0);
  detail = await mission.removeRunnerQueueItem(runner.id, detail.queue.items[0].id, detail.queue.revision);
  assert.deepEqual(detail.queue.items.map((item) => item.plan), ['two.md']);
});

